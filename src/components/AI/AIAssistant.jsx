/**
 * Floating AI Assistant Component
 */
const AIAssistant = () => {
  const location = useLocation();
  const navigate = useNavigate();
  const { user } = useAuth();

  const [isOpen, setIsOpen] = useState(false);
  const [isMinimized, setIsMinimized] = useState(false);
  const [input, setInput] = useState("");
  const [isTyping, setIsTyping] = useState(false);
  const [copiedIndex, setCopiedIndex] = useState(null);
  const [showNotification, setShowNotification] = useState(true);

  // Session storage backed message history
  const [messages, setMessages] = useState(() => {
    try {
      const saved = sessionStorage.getItem("flowai_messages");
      if (saved) return JSON.parse(saved);
    } catch {
      // ignore
    }
    return [
      {
        id: "welcome",
        sender: "ai",
        text: `👋 Greetings! I'm **FlowAI**, your workspace copilot. How can I help optimize your team's velocity today?`,
        timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      },
    ];
  });

  const messagesEndRef = useRef(null);
  const inputRef = useRef(null);

  // Save messages to session storage
  useEffect(() => {
    try {
      sessionStorage.setItem("flowai_messages", JSON.stringify(messages));
    } catch {
      // ignore
    }
  }, [messages]);

  // Scroll to bottom on new message
  useEffect(() => {
    if (isOpen && !isMinimized) {
      messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
    }
  }, [messages, isOpen, isMinimized, isTyping]);

  // Keyboard shortcut: Cmd/Ctrl + K to toggle
  useEffect(() => {
    const handleKeyDown = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "k") {
        e.preventDefault();
        setIsOpen((prev) => !prev);
        setIsMinimized(false);
      } else if (e.key === "Escape" && isOpen) {
        setIsOpen(false);
      }
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [isOpen]);

  // Focus input when opened
  useEffect(() => {
    if (isOpen && !isMinimized) {
      setTimeout(() => inputRef.current?.focus(), 150);
    }
  }, [isOpen, isMinimized]);

  // Dismiss proactive notification after 9s
  useEffect(() => {
    const timer = setTimeout(() => setShowNotification(false), 9000);
    return () => clearTimeout(timer);
  }, []);

  // Contextual quick suggestions based on current pathname & role
  const quickSuggestions = useMemo(() => {
    const p = location.pathname;
    if (p.includes("/admin")) {
      return [
        "Draft High-Priority Backend Task",
        "How to optimize sprint velocity?",
        "Explain RBAC security boundaries",
      ];
    } else if (p.includes("/employee")) {
      return [
        "What should I work on next?",
        "How to report a task blocker?",
        "Explain sprint velocity metrics",
      ];
    } else {
      return [
        "How does role security work?",
        "Draft a sample engineering task",
        "Guide me through workspace setup",
      ];
    }
  }, [location.pathname]);

  const handleSendMessage = async (textToSend = input) => {
    const prompt = textToSend.trim();
    if (!prompt || isTyping) return;

    const userMessage = {
      id: Date.now().toString(),
      sender: "user",
      text: prompt,
      timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
    };

    setMessages((prev) => [...prev, userMessage]);
    setInput("");
    setIsTyping(true);

    try {
      const responseData = await callGeminiAPI(prompt, location.pathname, user);
      const aiMessage = {
        id: (Date.now() + 1).toString(),
        sender: "ai",
        ...responseData,
        timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      };
      setMessages((prev) => [...prev, aiMessage]);
    } catch (err) {
      console.warn("FlowAI: Gemini API call failed, falling back to local engine:", err);
      const fallbackData = generateAIResponse(prompt, location.pathname, user);
      const aiMessage = {
        id: (Date.now() + 1).toString(),
        sender: "ai",
        ...fallbackData,
        timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      };
      setMessages((prev) => [...prev, aiMessage]);
    } finally {
      setIsTyping(false);
    }
  };

  const handleCopyTask = (task, index) => {
    const formatted = `TITLE: ${task.title}\nCATEGORY: ${task.category}\nPRIORITY: ${task.priority}\nDUE: ${task.dueDate}\n\nDESCRIPTION:\n${task.description}\n\nACCEPTANCE CRITERIA:\n${task.acceptanceCriteria.map((c) => `- ${c}`).join("\n")}`;
    navigator.clipboard.writeText(formatted);
    setCopiedIndex(index);
    setTimeout(() => setCopiedIndex(null), 2500);
  };

  const handleResetChat = () => {
    const initial = [
      {
        id: Date.now().toString(),
        sender: "ai",
        text: `Chat reset. Ready with fresh context for **${location.pathname}**. What would you like to build or orchestrate?`,
        timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      },
    ];
    setMessages(initial);
  };

  // Helper to format basic markdown-style bold and lists
  const renderFormattedText = (rawText) => {
    if (!rawText) return null;
    const lines = rawText.split("\n");
    return lines.map((line, idx) => {
      if (line.startsWith("### ")) {
        return (
          <h4 key={idx} className="font-bold text-[#101827] text-xs sm:text-sm mt-2 mb-1">
            {line.replace("### ", "")}
          </h4>
        );
      }
      if (line.startsWith("* ") || line.startsWith("- ")) {
        return (
          <li key={idx} className="ml-4 text-xs text-[#334155] list-disc my-0.5">
            <span
              dangerouslySetInnerHTML={{
                __html: line
                  .slice(2)
                  .replace(/\*\*(.*?)\*\*/g, '<strong class="text-[#101827] font-semibold">$1</strong>')
                  .replace(/`([^`]+)`/g, '<code class="px-1 py-0.5 rounded bg-[#F1F5F9] text-[#4F46E5] font-mono text-[11px]">$1</code>'),
              }}
            />
          </li>
        );
      }
      if (/^\d+\.\s/.test(line)) {
        return (
          <div key={idx} className="ml-2 text-xs text-[#334155] my-0.5">
            <span
              dangerouslySetInnerHTML={{
                __html: line
                  .replace(/\*\*(.*?)\*\*/g, '<strong class="text-[#101827] font-semibold">$1</strong>')
                  .replace(/`([^`]+)`/g, '<code class="px-1 py-0.5 rounded bg-[#F1F5F9] text-[#4F46E5] font-mono text-[11px]">$1</code>'),
              }}
            />
          </div>
        );
      }
      if (!line.trim()) {
        return <div key={idx} className="h-1.5" />;
      }
      return (
        <p
          key={idx}
          className="text-xs text-[#334155] leading-relaxed my-0.5"
          dangerouslySetInnerHTML={{
            __html: line
              .replace(/\*\*(.*?)\*\*/g, '<strong class="text-[#101827] font-semibold">$1</strong>')
              .replace(/`([^`]+)`/g, '<code class="px-1 py-0.5 rounded bg-[#F1F5F9] text-[#4F46E5] font-mono text-[11px]">$1</code>'),
          }}
        />
      );
    });
  };

  const getContextBadge = () => {
    const p = location.pathname;
    if (p.includes("/admin")) return { label: "Admin Center", color: "text-[#4F46E5] bg-[#EEF2FF] border-[#C7D2FE]" };
    if (p.includes("/employee")) return { label: "Employee Queue", color: "text-[#0284C7] bg-[#F0F9FF] border-[#BAE6FD]" };
    if (p.includes("/login") || p.includes("/signup")) return { label: "Auth Portal", color: "text-[#D97706] bg-[#FFFBEB] border-[#FDE68A]" };
    return { label: "Overview", color: "text-[#64748B] bg-[#F8FAFC] border-[#E2E8F0]" };
  };

  const currentBadge = getContextBadge();

  return (
    <div className="fixed bottom-5 right-5 z-50 select-none">
      {/* ─── Proactive Thought Bubble ─── */}
      {!isOpen && showNotification && (
        <div className="hidden sm:flex items-center gap-3 absolute bottom-16 right-0 mb-2 bg-white p-3.5 rounded-2xl border border-[#E1E5E9] shadow-xl max-w-xs animate-toast-enter">
          <div className="w-8 h-8 rounded-xl bg-[#101827] flex items-center justify-center text-white shrink-0 shadow-sm">
            <Bot className="w-4 h-4" />
          </div>
          <div className="text-left">
            <div className="text-[11px] font-bold text-[#101827] flex items-center gap-1.5">
              FlowAI Copilot
              <span className="w-1.5 h-1.5 rounded-full bg-[#10B981] animate-pulse" />
            </div>
            <p className="text-[10px] text-[#64748B] leading-tight mt-0.5">
              Need assistance delegating tasks or navigating? Press{" "}
              <kbd className="px-1 py-0.5 rounded bg-[#F1F5F9] border border-[#E1E5E9] text-[#475569] font-mono text-[9px]">
                ⌘K
              </kbd>
            </p>
          </div>
          <button
            onClick={() => setShowNotification(false)}
            className="text-[#94A3B8] hover:text-[#101827] p-1 ml-1"
          >
            <X className="w-3.5 h-3.5" />
          </button>
        </div>
      )}

      {/* ─── Floating Circular Trigger Button ─── */}
      {!isOpen && (
        <button
          onClick={() => {
            setIsOpen(true);
            setIsMinimized(false);
            setShowNotification(false);
          }}
          className="relative group p-3.5 rounded-2xl bg-[#101827] hover:bg-[#1E293B] text-white shadow-xl hover:shadow-2xl hover:scale-105 active:scale-95 transition-all duration-300 flex items-center gap-2.5 cursor-pointer border border-[#1E293B]"
          aria-label="Open AI Assistant"
        >
          {/* Pulsing Beacon */}
          <span className="absolute -top-1 -right-1 flex h-3 w-3">
            <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-[#10B981] opacity-75" />
            <span className="relative inline-flex rounded-full h-3 w-3 bg-[#10B981] border-2 border-white" />
          </span>

          <Bot className="w-5 h-5 text-white" />
          <span className="text-xs font-bold tracking-tight pr-1 hidden sm:inline">
            FlowAI
          </span>
          <span className="hidden sm:inline-block px-1.5 py-0.5 rounded-md bg-white/15 text-[10px] font-mono text-white/90">
            ⌘K
          </span>
        </button>
      )}

      {/* ─── Expanded AI Chat Modal ─── */}
      {isOpen && (
        <div
          className={`bg-white border border-[#E1E5E9] shadow-2xl rounded-2xl overflow-hidden transition-all duration-300 flex flex-col ${
            isMinimized
              ? "w-80 h-14"
              : "w-[92vw] sm:w-110 h-145 max-h-[86vh]"
          }`}
        >
          {/* Header Bar */}
          <div className="flex items-center justify-between px-4 py-3 bg-[#101827] text-white shrink-0">
            <div className="flex items-center gap-2.5">
              <div className="relative">
                <div className="w-8 h-8 rounded-xl bg-white/10 flex items-center justify-center text-white">
                  <Bot className="w-4 h-4" />
                </div>
                <span className="absolute -bottom-0.5 -right-0.5 w-2 h-2 rounded-full bg-[#10B981] border border-[#101827]" />
              </div>
              <div>
                <div className="flex items-center gap-2">
                  <h3 className="font-bold text-white text-xs sm:text-sm leading-none">
                    FlowAI Copilot
                  </h3>
                  <span
                    className={`text-[10px] font-semibold px-2 py-0.5 rounded-full border ${currentBadge.color}`}
                  >
                    {currentBadge.label}
                  </span>
                </div>
                <span className="text-[10px] text-[#94A3B8] flex items-center gap-1.5">
                  Senior Dev Copilot
                  <span className="text-[9px] text-[#A5B4FC] font-semibold flex items-center gap-0.5">
                    • <Sparkles className="w-2.5 h-2.5 text-[#A5B4FC] inline" /> Gemini Flash
                  </span>
                </span>
              </div>
            </div>

            <div className="flex items-center gap-1 text-[#94A3B8]">
              <button
                onClick={handleResetChat}
                title="Reset Conversation"
                className="p-1.5 rounded-lg hover:bg-white/10 hover:text-white transition-colors cursor-pointer"
              >
                <RotateCcw className="w-3.5 h-3.5" />
              </button>
              <button
                onClick={() => setIsMinimized((prev) => !prev)}
                title={isMinimized ? "Expand" : "Minimize"}
                className="p-1.5 rounded-lg hover:bg-white/10 hover:text-white transition-colors cursor-pointer"
              >
                {isMinimized ? (
                  <Maximize2 className="w-3.5 h-3.5" />
                ) : (
                  <Minimize2 className="w-3.5 h-3.5" />
                )}
              </button>
              <button
                onClick={() => setIsOpen(false)}
                title="Close (Esc)"
                className="p-1.5 rounded-lg hover:bg-white/10 hover:text-white transition-colors cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>
          </div>

          {/* Body Content */}
          {!isMinimized && (
            <>
              {/* Message Feed */}
              <div className="flex-1 overflow-y-auto p-4 space-y-4 text-left bg-[#F8FAFC]">
                {messages.map((msg, idx) => (
                  <div
                    key={msg.id || idx}
                    className={`flex flex-col ${
                      msg.sender === "user" ? "items-end" : "items-start"
                    }`}
                  >
                    <div
                      className={`max-w-[88%] rounded-2xl px-3.5 py-2.5 text-xs shadow-xs ${
                        msg.sender === "user"
                          ? "bg-[#101827] text-white rounded-tr-xs"
                          : "bg-white border border-[#E1E5E9] text-[#1E293B] rounded-tl-xs"
                      }`}
                    >
                      {msg.sender === "ai" ? (
                        renderFormattedText(msg.text)
                      ) : (
                        <p className="leading-relaxed whitespace-pre-wrap">{msg.text}</p>
                      )}

                      {/* Structured Task Draft Card */}
                      {msg.type === "task_draft" && msg.task && (
                        <div className="mt-3 p-3.5 rounded-xl bg-[#F1F5F9] border border-[#CBD5E1] text-left space-y-2">
                          <div className="flex items-center justify-between">
                            <span className="text-[10px] uppercase font-bold text-[#D97706]">
                              {msg.task.priority} Priority · {msg.task.category}
                            </span>
                            <span className="text-[10px] text-[#64748B]">
                              Due: {msg.task.dueDate}
                            </span>
                          </div>

                          <div className="font-bold text-[#101827] text-xs">
                            {msg.task.title}
                          </div>

                          <p className="text-[11px] text-[#475569] leading-snug">
                            {msg.task.description}
                          </p>

                          {msg.task.acceptanceCriteria && (
                            <div className="pt-2 border-t border-[#E2E8F0]">
                              <span className="text-[10px] uppercase font-bold text-[#64748B] block mb-1">
                                Acceptance Criteria
                              </span>
                              <ul className="space-y-1">
                                {msg.task.acceptanceCriteria.map((c, i) => (
                                  <li
                                    key={i}
                                    className="text-[10px] text-[#334155] flex items-start gap-1.5"
                                  >
                                    <Check className="w-3 h-3 text-[#059669] shrink-0 mt-0.5" />
                                    <span>{c}</span>
                                  </li>
                                ))}
                              </ul>
                            </div>
                          )}

                          <button
                            onClick={() => handleCopyTask(msg.task, idx)}
                            className="w-full mt-2 py-1.5 px-3 rounded-lg bg-white hover:bg-[#F8FAFC] border border-[#CBD5E1] text-[#101827] text-[11px] font-semibold flex items-center justify-center gap-1.5 transition-colors cursor-pointer shadow-xs"
                          >
                            {copiedIndex === idx ? (
                              <>
                                <CheckCircle2 className="w-3.5 h-3.5 text-[#059669]" />
                                <span>Copied Spec to Clipboard!</span>
                              </>
                            ) : (
                              <>
                                <Copy className="w-3.5 h-3.5 text-[#64748B]" />
                                <span>Copy Deliverable Spec</span>
                              </>
                            )}
                          </button>
                        </div>
                      )}

                      {/* Optional Context Action Link */}
                      {msg.action && (
                        <div className="mt-2.5 pt-2 border-t border-[#E1E5E9]">
                          <button
                            onClick={() => {
                              navigate(msg.action.path);
                              setIsOpen(false);
                            }}
                            className="inline-flex items-center gap-1.5 text-[11px] font-bold text-[#4F46E5] hover:text-[#4338CA] transition-colors cursor-pointer"
                          >
                            <span>{msg.action.label}</span>
                            <ArrowRight className="w-3 h-3" />
                          </button>
                        </div>
                      )}
                    </div>

                    <span className="text-[9px] text-[#94A3B8] mt-1 px-1">
                      {msg.timestamp}
                    </span>
                  </div>
                ))}

                {/* Live Typing Indicator */}
                {isTyping && (
                  <div className="flex items-center gap-2 p-2.5 rounded-xl bg-white border border-[#E1E5E9] w-20 shadow-xs">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#4F46E5] animate-bounce" />
                    <span
                      className="w-1.5 h-1.5 rounded-full bg-[#6366F1] animate-bounce"
                      style={{ animationDelay: "150ms" }}
                    />
                    <span
                      className="w-1.5 h-1.5 rounded-full bg-[#818CF8] animate-bounce"
                      style={{ animationDelay: "300ms" }}
                    />
                  </div>
                )}
                <div ref={messagesEndRef} />
              </div>

              {/* Quick Suggestions Chips */}
              <div className="px-3 py-2 bg-white border-t border-[#E1E5E9] flex items-center gap-1.5 overflow-x-auto">
                <Lightbulb className="w-3.5 h-3.5 text-[#F59E0B] shrink-0 ml-1" />
                {quickSuggestions.map((suggestion, i) => (
                  <button
                    key={i}
                    onClick={() => handleSendMessage(suggestion)}
                    className="whitespace-nowrap px-2.5 py-1 rounded-full bg-[#F1F5F9] hover:bg-[#E2E8F0] border border-[#E1E5E9] text-[#475569] hover:text-[#101827] text-[10px] font-medium transition-colors cursor-pointer shrink-0"
                  >
                    {suggestion}
                  </button>
                ))}
              </div>

              {/* Input Bar */}
              <div className="p-3 bg-white border-t border-[#E1E5E9]">
                <form
                  onSubmit={(e) => {
                    e.preventDefault();
                    handleSendMessage();
                  }}
                  className="flex items-center gap-2"
                >
                  <input
                    ref={inputRef}
                    type="text"
                    value={input}
                    onChange={(e) => setInput(e.target.value)}
                    placeholder="Ask FlowAI or request a task spec..."
                    className="flex-1 bg-white border border-[#E1E5E9] focus:border-[#4F46E5] focus:ring-1 focus:ring-[#4F46E5] px-3.5 py-2.5 rounded-xl text-xs text-[#101827] placeholder-[#94A3B8] focus:outline-none transition-all"
                  />
                  <button
                    type="submit"
                    disabled={!input.trim() || isTyping}
                    className="p-2.5 rounded-xl bg-[#101827] hover:bg-[#1E293B] text-white disabled:opacity-40 disabled:cursor-not-allowed shadow-xs cursor-pointer transition-transform active:scale-95 shrink-0"
                    aria-label="Send query"
                  >
                    <Send className="w-4 h-4" />
                  </button>
                </form>
                <div className="flex items-center justify-between text-[9px] text-[#94A3B8] mt-1.5 px-1">
                  <span>Context-aware for {user?.name ? `${user.name} (${user.role})` : "Guest"}</span>
                  <span>Esc to close</span>
                </div>
              </div>
            </>
          )}
        </div>
      )}
    </div>
  );
};

export default AIAssistant;
