const GEMINI_API_KEY = import.meta.env.VITE_GEMINI_API_KEY || "";

/**
 * Call live Gemini 3.6 Flash API with workspace context
 */
const callGeminiAPI = async (userPrompt, pathname, user) => {
  if (!GEMINI_API_KEY) {
    throw new Error("Missing Gemini API Key");
  }

  const role = user?.role || "guest";
  const userName = user?.name || "Workspace Member";
  const companyName = user?.companyName || "TeamFlow Workspace";

  const systemInstruction = `You are FlowAI, a world-class Senior Engineering Lead, Solutions Architect, and workspace copilot built directly into TeamFlow (an enterprise Employee Management System).
User Context:
- Name: ${userName}
- Role: ${role} (Roles are 'admin' or 'employee' or 'guest')
- Company: ${companyName}
- Current App Route: ${pathname}

Key TeamFlow Domain Knowledge:
- Admin Role: Manages team members, delegates tasks with priorities/categories/deadlines, monitors sprint velocity and aggregated status charts.
- Employee Role: Focuses on execution, views "Next Best Action", accepts deliverables ('new' -> 'active'), marks completed, or documents failed blockers for review.
- Tasks: Have title, category (Frontend, Backend, Database, Security, DevOps, Design, QA), priority (High, Medium, Low), dueDate, status (new, active, completed, failed).

Formatting Instructions:
1. When the user asks to create, draft, design, or generate a task or deliverable spec, you MUST include a JSON code block in the format:
\`\`\`json
{
  "type": "task_draft",
  "title": "Clear concise deliverable title",
  "category": "Frontend | Backend | Database | Security | DevOps",
  "priority": "High | Medium | Low",
  "dueDate": "e.g. In 3 days",
  "description": "2-3 sentences explaining architectural objective and scope",
  "acceptanceCriteria": [
    "Criteria 1",
    "Criteria 2",
    "Criteria 3"
  ]
}
\`\`\`
Followed or preceded by a brief professional note.
2. For all other technical, role, workflow, or architectural queries, provide crisp, senior-dev level markdown with bullet points, bold key terms, and code snippets where relevant. Keep answers concise, actionable, and encouraging.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.6-flash:generateContent?key=${encodeURIComponent(
    GEMINI_API_KEY.trim()
  )}`;

  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      system_instruction: {
        parts: [{ text: systemInstruction }],
      },
      contents: [
        {
          role: "user",
          parts: [{ text: userPrompt }],
        },
      ],
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 1000,
      },
    }),
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Gemini API error ${response.status}: ${errorText}`);
  }

  const data = await response.json();
  const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text || "";

  if (!rawText) {
    throw new Error("Empty response from Gemini API");
  }

  // Check if response contains a task JSON block
  const jsonMatch = rawText.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  if (jsonMatch) {
    try {
      const parsed = JSON.parse(jsonMatch[1]);
      if (parsed.title || parsed.type === "task_draft") {
        const remainingText = rawText
          .replace(/```(?:json)?\s*[\s\S]*?\s*```/, "")
          .trim();
        return {
          type: "task_draft",
          text:
            remainingText ||
            "Here is the deliverable spec generated by FlowAI via Gemini Flash:",
          task: {
            title: parsed.title || "Engineering Deliverable",
            category: parsed.category || "Development",
            priority: parsed.priority || "Medium",
            dueDate: parsed.dueDate || "Next Sprint",
            description: parsed.description || "",
            acceptanceCriteria: Array.isArray(parsed.acceptanceCriteria)
              ? parsed.acceptanceCriteria
              : [
                  "Verify implementation against unit and integration tests.",
                  "Enforce role-based access control and token validation.",
                  "Submit PR for senior peer review.",
                ],
          },
          action:
            role === "admin"
              ? { label: "Open Task Creator", path: "/admin" }
              : null,
          source: "gemini",
        };
      }
    } catch {
      // JSON parse failed, fall through to regular markdown
    }
  }

  return {
    type: "text",
    text: rawText,
    action:
      role === "admin"
        ? { label: "Open Admin Center", path: "/admin" }
        : role === "employee"
        ? { label: "Go to Deliverables", path: "/employee" }
        : null,
    source: "gemini",
  };
};

